import { Brain } from "../brain.ts"
import { Brain as BrainV1 } from "./brain_v1.ts"
import { Brain as BrainPro } from "./brain_pro.ts"
import { Brain as BrainS } from "./brain_s.ts"
import type { GameMap } from "../map.ts"
import { Idle, Example } from "./opponents.ts"
import { ZoneBot } from "../zonebot.ts"
export function make(kind: string, h: any, m: GameMap): any {
  if (kind === "hunter") return new BrainV1(h, m, { aggression: 0.9 })
  if (kind === "v1") return new BrainV1(h, m, {})
  if (kind === "pro") return new BrainPro(h, m, { aggression: 1.0, hunt: true, lootFar: true, coverCheck: true })
  if (kind === "noduck") return new Brain(h, m, { duck: false })
  if (kind === "center") return new Brain(h, m, { homeMode: "center" })
  if (kind === "edgenofarm") return new Brain(h, m, { farm: false })
  if (kind === "loud") return new Brain(h, m, { stealth: false })
  if (kind === "stealthy") return new Brain(h, m, { style: "stealth" })
  if (kind === "nojink") return new Brain(h, m, { jink: false })
  if (kind === "idle") return new Idle()
  if (kind === "example") return new Example()
  if (kind === "surv") return new BrainS(h, m, { style: "stealth" })
  if (kind === "survf") return new BrainS(h, m, {})
  if (kind === "v5like") return new Brain(h, m, { style: "stealth", jink: false, zoneFirst: false, lootFar: false })
  if (kind === "pro2") { const b: any = new BrainPro(h, m, { aggression: 1.0, hunt: true, lootFar: true, heal: true }); b.omni = true; return b }
  if (kind === "pro3") { const b: any = new BrainPro(h, m, { aggression: 1.0, hunt: true, lootFar: true, heal: true }); return b }
  if (kind === "survfarm") return new BrainS(h, m, { style: "stealth", farm: true })
  if (kind === "sfarm") return new Brain(h, m, { style: "stealth", farm: true })
  if (kind === "noroof") return new Brain(h, m, { roof: false })
  if (kind === "zone") return new ZoneBot(h, m)
  if (kind === "f1") return new Brain(h, m, { style: "fighter", roof: false, aggression: 1.0 })
  if (kind === "f2") return new Brain(h, m, { style: "fighter", roof: false, aggression: 1.0, hunt: true })
  if (kind === "f3") return new Brain(h, m, { stealth: false, style: "x", roof: false, aggression: 1.0 })
  if (kind === "f4") return new Brain(h, m, { stealth: false, style: "x", roof: false, aggression: 1.0, farm: false })
  if (kind === "f2nf") return new Brain(h, m, { style: "fighter", roof: false, aggression: 1.0, hunt: true, focus: false })
  if (kind === "f2c") return new Brain(h, m, { style: "fighter", roof: false, aggression: 1.0, hunt: true, chase: true })
  if (kind === "t1") return new Brain(h, m, { stealth: false, style: "x", roof: false, aggression: 1.0, chase: true, tactical: true })
  if (kind === "t2") return new Brain(h, m, { style: "fighter", roof: false, aggression: 1.0, hunt: true, focus: false, tactical: true })
  if (kind === "t3") return new Brain(h, m, { stealth: false, style: "x", roof: false, aggression: 1.0, chase: true, tactical: true, precharge: true })
  if (kind === "f3p") return new Brain(h, m, { stealth: false, style: "x", roof: false, aggression: 1.0, chase: true, precharge: true })
  if (kind === "mainp") return new Brain(h, m, { precharge: true })
  if (kind === "sfh") return new Brain(h, m, { roof: false, farmHard: true })
  if (kind === "f2fh") return new Brain(h, m, { style: "fighter", roof: false, aggression: 1.0, hunt: true, focus: false, farmHard: true })
  if (kind === "f3fh") return new Brain(h, m, { stealth: false, style: "x", roof: false, aggression: 1.0, chase: true, farmHard: true })
  if (kind === "sq") return new Brain(h, m, { style: "squad", roof: false, farmHard: true })
  if (kind === "sqt") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, tactical: true, precharge: true })
  if (kind === "sq200") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 200 })
  if (kind === "sq80") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 80 })
  if (kind === "sqnf") return new Brain(h, m, { style: "squad", roof: false })
  if (kind === "sqr") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 80, rearBonus: 250 })
  if (kind === "sqrs") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 80, rearBonus: 250, stillPassive: true })
  if (kind === "sqp") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 80, rearBonus: 250, stillPassive: true, prowl: true })
  if (kind === "sql") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 80, rearBonus: 250, stillPassive: true, prefRange: 170 })
  if (kind === "sqb") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 80, rearBonus: 250, stillPassive: true, prowl: true, fightBoost: true })
  if (kind === "v1b") return new BrainV1(h, m, {})
  if (kind === "sqz") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 80, rearBonus: 250, stillPassive: true, prowl: true, wprio: { lightning: 3, laser: 2, mortar: 1, gun: 0 } })
  if (kind === "hbx") return new Brain(h, m, { style: "fighter", roof: false, aggression: 1.0, hunt: true, focus: false, fightBoost: true })
  if (kind === "sqm") return new Brain(h, m, { style: "squad", roof: false, farmHard: true, huntGap: 80, rearBonus: 250, stillPassive: true, prowl: true, fightBoost: true, precharge: true, gunDisc: true })
  if (kind === "f3c") return new Brain(h, m, { stealth: false, style: "x", roof: false, aggression: 1.0, chase: true })
  if (kind === "nocover") return new Brain(h, m, { coverCheck: false })
  if (kind === "noloot") return new Brain(h, m, { lootFar: false })
  if (kind === "base2") return new Brain(h, m, { coverCheck: false, lootFar: false })
  if (kind === "main") return new Brain(h, m, {})
  if (kind === "agg") return new Brain(h, m, { aggression: 0.9 })
  if (kind === "timid") return new Brain(h, m, { aggression: 0.2 })
  if (kind === "nofarm") return new Brain(h, m, { farm: false })
  if (kind.startsWith("agg:")) return new Brain(h, m, { aggression: +kind.slice(4) })
  throw new Error("unknown variant " + kind)
}
